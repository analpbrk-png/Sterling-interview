/**
 * Generates supabase/seed.sql from data/question-import/cas-shield.json.
 * Run: npm run seed:build
 *
 * Every imported question lands as pending_review + inactive. An admin reviews
 * and approves them in Admin → Questions → Review before students see any.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { SYSTEM_CATEGORIES } from "../src/lib/questions/categories";
import {
  detectCountryInconsistency,
  detectPolicyConflicts,
  detectSensitivity,
  detectUniversityMention,
  groupSimilar,
} from "../src/lib/questions/analysis";

interface Item {
  page: number;
  type?: string;
  category: string;
  prep?: number;
  answer?: number;
  submission?: string;
  source_text: string;
  question_text: string;
  review_note?: string;
  pronunciation_words?: string[];
}
interface Source {
  file: string;
  pages: number;
  skipped_pages: Record<string, string>;
  items: Item[];
}

const data = JSON.parse(readFileSync("data/question-import/cas-shield.json", "utf8")) as { sources: Source[] };

const uuid = (seed: string) => {
  const h = createHash("sha256").update(seed).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));

const out: string[] = [
  "-- GENERATED by scripts/build-seed.ts from data/question-import/cas-shield.json. Do not edit by hand.",
  "begin;",
  "",
  "-- Question categories",
];
for (const c of SYSTEM_CATEGORIES) {
  out.push(
    `insert into public.question_categories (id, name, sort_order, is_system) values (${q(c.id)}, ${q(c.name)}, ${c.sort}, true) on conflict (id) do update set name = excluded.name, sort_order = excluded.sort_order, is_system = true;`,
  );
}

out.push("", "-- Admin settings (no secrets)");
const settings: Record<string, unknown> = {
  ai_enabled: true,
  ai_max_questions_per_session: 6,
  document_retention_days: 365,
  tts_rate: 0.95,
};
for (const [k, v] of Object.entries(settings)) {
  out.push(
    `insert into public.admin_settings (key, value) values (${q(k)}, ${q(JSON.stringify(v))}::jsonb) on conflict (key) do nothing;`,
  );
}

out.push("", "-- Default UK template");
out.push(`insert into public.interview_templates
  (id, name, country, is_default, identity_enabled, name_id_step_enabled, pronunciation_enabled, pronunciation_words,
   declaration_enabled, declaration_text, prep_seconds, answer_seconds, submission_mode, allow_early_submit,
   question_count, ai_question_count, include_sensitive, tts_default)
values (${q(uuid("template:uk-default"))}, 'UK CAS Shield Practice', 'UK', true, true, true, true,
  array['Hocus-pocus','Jibber-jabber','Babbling'], true,
  ${q("I confirm that I understand the seriousness of this interview process and acknowledge that any instance of cheating, attempted deception, or fraud on my part will result in the withdrawal of my admission offer.")},
  20, 60, 'automatic', true, 12, 4, false, true)
on conflict (id) do nothing;`);

// Flatten items with stable keys, then group similar wording across all files.
const flat = data.sources.flatMap((s) => s.items.map((it) => ({ src: s, it, key: `${s.file}#${it.page}` })));
const groups = groupSimilar(flat.map((f) => ({ key: f.key, text: f.it.question_text })));

let imported = 0;
for (const s of data.sources) {
  const sourceId = uuid(`source:${s.file}`);
  const skipped = Object.entries(s.skipped_pages)
    .map(([p, r]) => `p${p}: ${r}`)
    .join("; ");
  out.push(
    "",
    `-- Source: ${s.file} (${s.pages} pages)`,
    `insert into public.question_sources (id, file_name, kind, page_count, notes) values (${q(sourceId)}, ${q(s.file)}, 'pdf', ${s.pages}, ${q(`Pages without questions: ${skipped}`)}) on conflict (id) do nothing;`,
  );
}

for (const { src, it, key } of flat) {
  const id = uuid(`question:${key}`);
  const type = it.type ?? "question";
  const sens = type === "question" ? detectSensitivity(it.source_text) : { sensitive: false, reason: null };
  const uni = detectUniversityMention(it.source_text);
  const g = groups.get(key)!;
  const notes = [
    it.review_note,
    detectCountryInconsistency(it.source_text, "UK"),
    ...detectPolicyConflicts(it.source_text),
    uni ? `Mentions ${uni}: only show to students applying there (set applicable universities).` : null,
    g.duplicateOf ? `Duplicate of ${g.duplicateOf.replace("#", " page ")}.` : null,
    !g.duplicateOf && g.bestScore < 1 ? `Similar to other questions in group ${g.group} (score ${g.bestScore.toFixed(2)}).` : null,
    type !== "question" ? "Intro step: used through the interview template (identity / pronunciation / declaration), not as a timed question." : null,
  ].filter(Boolean);
  const dupId = g.duplicateOf ? uuid(`question:${g.duplicateOf}`) : null;
  out.push(
    `insert into public.question_bank (id, question_text, source_text, source_id, source_file, source_page, origin, question_type, category_id, country, mentions_university, prep_seconds, answer_seconds, submission_mode, is_mandatory, is_sensitive, sensitivity_reason, is_active, review_status, review_notes, similarity_group, duplicate_of) values (${q(id)}, ${q(it.question_text)}, ${q(it.source_text)}, ${q(uuid(`source:${src.file}`))}, ${q(src.file)}, ${it.page}, 'imported', ${q(type)}, ${q(it.category)}, 'UK', ${q(uni)}, ${n(it.prep)}, ${n(it.answer)}, ${it.submission ? q(it.submission) : "null"}, false, ${sens.sensitive}, ${q(sens.reason)}, false, 'pending_review', ${q(notes.join("\n") || null)}, ${q(`pdf-${g.group}`)}, ${dupId ? q(dupId) : "null"}) on conflict do nothing;`,
  );
  imported++;
}

out.push("", "commit;", "");
writeFileSync("supabase/seed.sql", out.join("\n"));
console.log(`seed.sql written: ${imported} imported records from ${data.sources.length} files`);
